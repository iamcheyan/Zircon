    /// <summary>按 ClientSettings.Language 重新加载语言实例。切换语言后调用。</summary>
    public static void Reload()
    {
        // 命令行 --lang 优先（方便真机验证/测试），其次持久化设置。
        string lang = AutoLoginArgs.Language ?? ClientSettings.Language ?? "CHINESE";
        switch (lang.ToUpperInvariant())
        {
            case "ENGLISH":
                Current = new EnglishMessages();
                break;
            default:
                Current = new ChineseMessages();
                break;
        }
        try { Godot.GD.Print($"[Lang] 语言已加载: {lang} (autoLogin={AutoLoginArgs.Language ?? "null"}, settings={ClientSettings.Language ?? "null"})"); } catch { }
    }

